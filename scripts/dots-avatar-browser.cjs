// Local demo QA. Needs Playwright; no account or API fixtures are presented as production.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require('playwright')
const out = path.resolve(__dirname, '../test-results/dots-avatar')
;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || '/usr/bin/chromium', headless: true,
    args: ['--no-sandbox', '--disable-dev-shm-usage', '--enable-unsafe-swiftshader'] })
  const errors = []
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    page.setDefaultTimeout(60000)
    page.on('pageerror', error => errors.push(error.message))
    const settings = () => page.getByRole('button', { name: 'Настроить Dots', exact: true }).click()
    const host = page.locator('.og-companion .og-dots-character')
    const closed = () => page.locator('.og-dots-modal').waitFor({ state: 'detached' })
    await page.goto(process.env.DOTS_QA_URL || 'http://localhost:5173/?demo')
    await host.waitFor()
    assert.equal(await host.getAttribute('data-avatar'), 'cloud')
    await settings()
    await page.locator('input[value="cat"]').check()
    await page.getByLabel('Имя', { exact: true }).fill('Луна')
    await page.locator('input[value="flat"]').check()
    await page.getByRole('button', { name: 'Это мой Dots' }).click()
    await closed()
    await page.reload()
    await host.waitFor()
    assert.equal(await host.getAttribute('data-avatar'), 'cat')
    await settings()
    assert.equal(await page.getByLabel('Имя', { exact: true }).inputValue(), 'Луна')
    assert.equal(await page.locator('input[value="flat"]').isChecked(), true)
    await page.getByLabel('Живые анимации').uncheck()
    await page.getByRole('button', { name: 'Закрыть настройки Dots' }).click()
    await closed()
    assert.equal(await host.getAttribute('data-motion'), 'false')
    await page.waitForTimeout(200)
    const surface = host.locator('.og-dots-avatar-surface')
    const still = await surface.innerHTML()
    await page.waitForTimeout(350)
    assert.equal(await surface.innerHTML(), still)
    await settings()
    await page.locator('input[value="ghost"]').check()
    await page.goBack()
    await closed()
    assert.equal(await host.getAttribute('data-avatar'), 'cat')
    for (const [width, theme] of [[320, 'dark'], [390, 'light']]) {
      await page.setViewportSize({ width, height: 844 })
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await settings()
      await page.screenshot({ path: path.join(out, `qa-settings-${theme}-${width}.png`) })
      await page.getByRole('button', { name: 'Закрыть настройки Dots' }).click()
      await closed()
    }
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await settings()
    assert.equal(await page.getByLabel('Живые анимации').isDisabled(), true)
    await page.getByRole('button', { name: 'Закрыть настройки Dots' }).click()
    await closed()
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await settings()
    await page.getByLabel('Живые анимации').check()
    await page.getByRole('button', { name: 'Закрыть настройки Dots' }).click()
    await closed()
    await host.locator('canvas').waitFor()
    await host.locator('canvas').evaluate(canvas => canvas.dispatchEvent(new Event('contextlost')))
    await page.waitForTimeout(150)
    assert.equal(await host.getAttribute('data-motion'), 'false')
    assert.equal(await host.locator('canvas').count(), 0)
    assert.equal(await host.locator('.og-dots-avatar-poster').isVisible(), true)
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(out, 'qa.json'), JSON.stringify({ result: 'PASS', mode: 'local demo', errors }, null, 2))
    console.log('Dots avatar browser QA PASS: persistence, discard/Back, pause, themes, reduced motion, context loss')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
