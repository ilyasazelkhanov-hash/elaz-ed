export function lessonTerms(title: string, courseCode: string) {
  const haystack = `${title} ${courseGuide(courseCode)?.summary || ''}`.toLocaleLowerCase('ru')
  return academyGlossary.filter(([term]) => {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    return new RegExp(`(^|[^\\p{L}\\p{N}])${escaped}($|[^\\p{L}\\p{N}])`, 'iu').test(haystack)
  }).slice(0, 5)
}

export function nextAcademyLesson<T extends { code: string; state: string }>(lessons: T[], progress: { lesson_code: string; state?: string; status?: string; completed?: boolean }[]) {
  const completed = new Set(progress.filter(item => (item.state || item.status) === 'completed' || item.completed).map(item => item.lesson_code))
  return lessons.find(lesson => lesson.state === 'published' && !completed.has(lesson.code))
}
