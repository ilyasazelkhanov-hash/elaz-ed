export type CourseGuide = {
  summary: string
  scenario: string
  start: string
  example: string
  flow: string[]
  checks: string[]
  pitfall: string
}

export function courseGuide(code: string): CourseGuide | undefined {
  return (guides as Record<string, CourseGuide>)[code.replace(/-M\d+-L\d+$/, '')]
}

