export function lessonGuide(lesson: LessonInfo) {
  const guide = courseGuide(lesson.code)
  const d = lesson.data
  const artifact = asText(d.deliverable || d.artifact)
  const specificArtifact = artifact && !/^Артефакт занятия:/i.test(artifact)
  const hints = formatHints[String(d.format || d.lesson_type)] || formatHints.assignment
  return {
    guide,
    goal: specificArtifact ? artifact : `Короткий разбор темы «${lesson.title}»: пример, результат и способ его проверки.`,
    criteria: asText(d.criteria || d.acceptance).split('\n').filter(Boolean),
    hints,
    prompt: `Помоги мне разобраться в теме «${lesson.title}».${guide ? ` Учебная ситуация: ${guide.scenario}` : ''} Объясни на одном простом примере. Затем дай маленькое упражнение и критерии самопроверки. Не выполняй упражнение за меня; сначала дождись моей попытки. Если данных не хватает, задай вопрос.`,
  }
}

